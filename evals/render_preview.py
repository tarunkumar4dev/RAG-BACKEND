"""Render evals/sample_trigonometry_result.json -> preview HTML (CBSE layout, KaTeX) + review markdown."""
import html, json, os

D = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(D, "sample_trigonometry_result.json"), encoding="utf-8"))
bp, paper, s = d["blueprint"], d["paper"], d["summary"]
pq = s["per_question"]
SEC = {"A": "Section A — Objective (MCQ & Assertion-Reason), 1 mark each", "B": "Section B — Very short answer, 2 marks each",
       "C": "Section C — Short answer, 3 marks each", "D": "Section D — Long answer, 5 marks each",
       "E": "Section E — Case study, 4 marks"}
e = lambda t: html.escape(str(t or ""))
body, key = [], []
cur = None
for n, q in enumerate(paper["questions"], 1):
    if q["section"] != cur:
        cur = q["section"]
        body.append(f"<h2>{e(SEC.get(cur, 'Section ' + cur))}</h2>")
    opts = "".join(f"<li>({chr(97 + i)}) {e(o)}</li>" for i, o in enumerate(q.get("options") or []))
    subs = "".join(f"<li>{e(p['text'])} <span class='m'>[{p.get('marks')}]</span></li>" for p in (q.get("sub_questions") or []))
    badge = {"verified": "✔ verified", "rubric_ok": "✔ rubric checked", "manual_review": "⚠ manual review",
             "failed": "✖ failed"}[q["status"]]
    body.append(f"<div class='q'><div class='qh'><b>Q{n}.</b> <span class='m'>[{q['marks']:g}]</span> "
                f"<span class='b {q['status']}'>{badge}</span></div><div>{e(q['text'])}</div>"
                + (f"<ol class='o'>{opts}</ol>" if opts else "") + (f"<ol type='i'>{subs}</ol>" if subs else "") + "</div>")
    ans = q.get("answer")
    if q.get("options") and ans:
        ans = f"({str(ans).strip()[0].lower()})"
    scheme = "".join(f"<li>{e(m.get('step', m) if isinstance(m, dict) else m)}"
                     f"{' — ' + str(m.get('marks')) + ' m' if isinstance(m, dict) and m.get('marks') else ''}</li>"
                     for m in (q.get("marking_scheme") or []))
    sub_ans = "".join(f"<li>{e(p.get('answer'))}</li>" for p in (q.get("sub_questions") or []))
    key.append(f"<li><b>Q{n}</b> {e(ans) if ans else ''} {e(q.get('solution'))}"
               + (f"<ul>{scheme}</ul>" if scheme else "") + (f"<ol type='i'>{sub_ans}</ol>" if sub_ans else "") + "</li>")
summary = (f"Objective {s['objective_verified']}/{s['objective_total']} verified · Rubric {s['rubric_checked']}/"
           f"{s['rubric_total']} checked · {len(s['manual_review'])} manual review · marks sum {s['marks_sum']:g}/"
           f"{bp['total_marks']:g} {'✔' if s['marks_sum_ok'] else '✖'} · {s['rounds']} verification round(s)")
page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Trigonometry Test Preview</title>
<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/katex@0.16.11/dist/katex.min.css">
<script defer src="https://cdn.jsdelivr.net/npm/katex@0.16.11/dist/katex.min.js"></script>
<script defer src="https://cdn.jsdelivr.net/npm/katex@0.16.11/dist/contrib/auto-render.min.js"
 onload="renderMathInElement(document.body,{{delimiters:[{{left:'$$',right:'$$',display:true}},{{left:'$',right:'$',display:false}}],trust:false,throwOnError:false}})"></script>
<style>body{{font-family:Georgia,serif;max-width:820px;margin:0 auto;padding:16px;background:#fff;color:#111;line-height:1.5}}
header{{text-align:center;border-bottom:2px solid #111;padding-bottom:8px}}.meta{{display:flex;justify-content:space-between;font-size:14px}}
h2{{font-size:16px;background:#f2f2f2;padding:6px 8px;margin-top:24px}}.q{{margin:12px 0;overflow-wrap:anywhere}}.m{{color:#555}}
.o{{list-style:none;padding-left:16px;display:grid;grid-template-columns:repeat(auto-fit,minmax(160px,1fr))}}
.b{{font:12px system-ui;padding:1px 6px;border-radius:8px;margin-left:6px}}.verified,.rubric_ok{{background:#e6f4ea;color:#1e6b34}}
.manual_review{{background:#fff4e0;color:#8a5300}}.failed{{background:#fde8e8;color:#9b1c1c}}
.v{{font:13px system-ui;background:#f7f7f7;border:1px solid #ddd;padding:8px;margin:12px 0}}details{{margin-top:24px}}</style></head>
<body><header><div><b>CBSE — Class {bp['class_grade']} {e(bp['subject'])}</b></div><div>{e(bp['chapters'][0])} (NCERT)</div>
<div class="meta"><span>Time: {bp['duration_min']} min</span><span>Maximum Marks: {bp['total_marks']:g}</span></div></header>
<div class="v">{e(summary)}</div>
<p><i>General instructions: All questions are compulsory. Section A: Q{1}–Q{sum(1 for q in paper['questions'] if q['section']=='A')} carry 1 mark each.</i></p>
{''.join(body)}
<details><summary><b>Answer key & marking scheme (teacher only)</b></summary><ol style="list-style:none;padding:0">{''.join(key)}</ol></details>
<p class="m" style="font:12px system-ui">Generated by a4ai Agent · provider {e(d.get('provider'))} · NCERT source: {e(d.get('rag_source'))} · draft, not approved</p>
</body></html>"""
open(os.path.join(D, "sample_trigonometry_preview.html"), "w", encoding="utf-8").write(page)

rows = ["| Q | type | marks | solved independently? | sympy | key matches? | status | notes |", "|---|---|---|---|---|---|---|---|"]
for n, q in enumerate(paper["questions"], 1):
    r = pq[q["id"]]
    det = q["qtype"] in ("mcq", "numeric", "assertion_reason", "very_short")
    rows.append(f"| Q{n} ({q['id']}) | {q['qtype']} | {q['marks']:g} | "
                f"{('yes → ' + str(r.get('solver_answer'))) if det and r.get('solver_answer') else ('no (rubric)' if not det else 'no answer')} | "
                f"{r.get('sympy') or ('—' if not det else 'no check_expr')} | "
                f"{'—' if r.get('key_matches') is None else ('yes' if r['key_matches'] else 'NO')} | {r['status']} | "
                f"{'; '.join(r['reasons']) or '—'} |")
md = f"""# Trigonometry demo — per-question review

Request: "Class 10 CBSE trigonometry, NCERT se, all question types, 2-3 assertion reason, 1 case study, 40 marks".
Provider: **{d.get('provider')}** · latency {d.get('latency_s')} s · tokens in/out {d['usage'][0]}/{d['usage'][1]} · NCERT source: `{d.get('rag_source')}`.

**{summary}**

{chr(10).join(rows)}

## Errors found and fixed (3 runs)
- Run 1 (96 s, 3 rounds): q3/q4 "failed" were **verifier bugs**, not bad questions — `_norm` dropped the minus sign
  (`1` and `-1` looked identical) and `\\dfrac` parsed as `d·frac`. q13 (`A = 45°, B = 15°`) → manual review (multi-value).
  Fixed: LaTeX → sympy converter (innermost-first `\\sqrt`, `\\[dt]frac`, `^\\circ`, `\\sin^2 x`), value-based option
  distinctness, pairwise `A=…, B=…` comparison. Regression tests in `tests/agent/test_core_security.py`.
- Run 2 (51 s): 5 manual reviews — `Rational(7,5)` check expressions rejected by an over-strict guard (bug), and A-R
  options (prose) were pushed through sympy (meaningless). Fixed: allow `Rational`, A-R decided by independent solver +
  standard option set. Re-checking run 2's saved paper then exposed a **real** error: an A-R item where the key said
  (B) and the independent solver said (A) → now `failed` → regenerated. Also a "prove that" in a 2-mark value slot →
  manual review; generator prompt tightened (single final value; Class 10 syllabus has no compound-angle formulae).
- Run 3 (this file): result above.

Manual-review items are NOT counted as verified; a teacher must look at them before approval.
"""
open(os.path.join(D, "sample_trigonometry_review.md"), "w", encoding="utf-8").write(md)
print(summary)
